# Email settings
# Используйте переменные окружения для настройки email
# Для development без переменных окружения письма выводятся в консоль

# SMTP настройки (читаются из переменных окружения)
EMAIL_HOST = os.getenv('EMAIL_HOST', 'smtp.gmail.com')
EMAIL_PORT = int(os.getenv('EMAIL_PORT', '587'))
EMAIL_USE_TLS = os.getenv('EMAIL_USE_TLS', 'True').lower() == 'true'
EMAIL_USE_SSL = os.getenv('EMAIL_USE_SSL', 'False').lower() == 'true'
EMAIL_HOST_USER = os.getenv('EMAIL_HOST_USER', '')
EMAIL_HOST_PASSWORD = os.getenv('EMAIL_HOST_PASSWORD', '')

# Если указаны учетные данные, используем SMTP, иначе консоль для development
if EMAIL_HOST_USER and EMAIL_HOST_PASSWORD:
    # Используем кастомный backend для обработки проблем с SSL на macOS
    EMAIL_BACKEND = os.getenv('EMAIL_BACKEND', 'crm.email_backend.FixedEmailBackend')
    DEFAULT_FROM_EMAIL = os.getenv('DEFAULT_FROM_EMAIL', EMAIL_HOST_USER)
else:
    EMAIL_BACKEND = os.getenv('EMAIL_BACKEND', 'django.core.mail.backends.console.EmailBackend')
    DEFAULT_FROM_EMAIL = os.getenv('DEFAULT_FROM_EMAIL', 'noreply@shop.local')

